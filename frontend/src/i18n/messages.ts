/**
 * i18n 语言配置包 —— 中文 / 英文双语词条目录。
 *
 * 设计与 `app/theme.tsx` 同构：locale 只是一组键值覆盖，运行时由 provider 选取。
 * `en` 是**权威源**（source of truth），决定所有合法 key；`zh` 用 `Messages`
 * 类型强制对齐，因此漏翻一个 key 会在编译期报错，而非运行期静默回退。
 *
 * 词条用**扁平点分 key**（如 `nav.agents`），按区块用注释分组，便于检索与 diff。
 * 占位符用 `{{name}}` 形式，由 `provider.tsx` 的 `t()` 做插值。
 */

